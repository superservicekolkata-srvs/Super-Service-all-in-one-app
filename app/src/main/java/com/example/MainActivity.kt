class MainActivity : ComponentActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        enableEdgeToEdge()
        NotificationAlertHelper.init(applicationContext)
        setContent {
            MyApplicationTheme {
                AppNavigation()
            }
        }
    }
}

internal fun FirebaseAuth.authStateFlow(): Flow<FirebaseUser?> = callbackFlow {
    val listener = FirebaseAuth.AuthStateListener { auth ->
        trySend(auth.currentUser)
    }
    addAuthStateListener(listener)
    awaitClose { removeAuthStateListener(listener) }
}

@Composable
fun AppNavigation(auth: FirebaseAuth = Firebase.auth) {
    val currentUser by auth.authStateFlow().collectAsStateWithLifecycle(initialValue = auth.currentUser)
    val user = currentUser

    if (user == null) {
        AuthScreen(onAuthSuccess = {})
    } else {
        val uid = user.uid
        val isBootstrappedAdmin = user.isEmailVerified &&
            user.email.equals(SuperServiceRepository.BOOTSTRAPPED_ADMIN_EMAIL, ignoreCase = true)

        key(uid) {
            val viewModel: SuperServiceViewModel = viewModel(
                key = uid,
                factory = viewModelFactory {
                    initializer {
                        val app = checkNotNull(this[APPLICATION_KEY]) {
                            "APPLICATION_KEY missing from CreationExtras"
                        }
                        val databaseId = app.getString(R.string.firestore_database_id)
                        val db = FirebaseFirestore.getInstance(databaseId)
                        SuperServiceViewModel(
                            repository = SuperServiceRepository(db, Firebase.auth),
                            currentUserId = uid,
                            initialIsBootstrappedAdmin = isBootstrappedAdmin
                        )
                    }
                }
            )
            SuperServiceMainScreen(
                viewModel = viewModel,
                isBootstrappedAdmin = isBootstrappedAdmin,
                userEmail = user.email ?: ""
            )
        }
    }
}
